// Generator: produces the OFA banner (tall font, orange→blue fade) as a
// single ANSI-colored string, suitable for embedding in a Go binary.
//
// Uses the local ascii.rest banner source (no remote calls). The output
// is one frame, no animation: `effect: "still"`.
//
// Why not just call `npx ascii.rest`? Because that emits live ANSI control
// sequences that overwrite each other in place, not a static string we can
// paste into source.

import { banner } from "./banner.ts";
import { writeFileSync } from "node:fs";

const TEXT = "OFA";
const COLOR = ["#e67a4c", "#4282d7"]; // orange → blue
const FONT = "tall";

const piece = banner(TEXT, {
  font: FONT,
  color: COLOR,
  effect: "still",
});

const { meta } = piece;
if (!meta.palette) {
  throw new Error("expected a colored banner (palette set)");
}

// Drive the frame once with a color buffer; the frame writes palette
// indices into env.color per cell.
const cells = meta.cols * meta.rows;
const color = new Uint8Array(cells);
const frameStr = piece.default()(0, { paper: false, color });

// `steps` is the number of fade colors per theme. `half = steps + 1` is
// the boundary between the two palette halves (dark, light). See banner.ts:
//   palette.push(quiet, ...fade(stops, steps))   // per theme
//   const half = steps + 1
//   shadow cell:   color[k] = half
//   letter cell:   color[k] = half + 1 + bucket(c)
const steps = stepsOf(meta);
const half = steps + 1;
const shadowDark = meta.palette[0];
const fadeDark = meta.palette.slice(1, half);

const ansi = (rgb) => {
  const r = parseInt(rgb.slice(1, 3), 16);
  const g = parseInt(rgb.slice(3, 5), 16);
  const b = parseInt(rgb.slice(5, 7), 16);
  return `\x1b[38;2;${r};${g};${b}m`;
};
const reset = "\x1b[0m";

const lines = frameStr.split("\n");
if (lines.length !== meta.rows) {
  throw new Error(`row count mismatch: got ${lines.length}, meta=${meta.rows}`);
}

let out = "";
for (let r = 0; r < meta.rows; r++) {
  const row = lines[r];
  if (row.length !== meta.cols) {
    throw new Error(`col count mismatch on row ${r}: got ${row.length}, meta=${meta.cols}`);
  }
  for (let c = 0; c < meta.cols; c++) {
    const k = r * meta.cols + c;
    const ch = row[c];
    if (ch === " ") {
      // Empty cell — emit the space as-is so the baked string keeps the
      // banner's full cols×rows shape. Without it, downstream code that
      // measures width by rune count would see only the colored cells.
      out += " ";
      continue;
    }
    const idx = color[k];
    let rgb;
    if (idx === half) {
      // shadow cell
      rgb = shadowDark;
    } else if (idx > half) {
      // letter cell
      rgb = fadeDark[idx - half - 1] ?? shadowDark;
    } else {
      // idx == 0 — empty cell that the frame didn't mark (shouldn't happen
      // since we already checked ch === " ", but be safe).
      out += " ";
      continue;
    }
    out += ansi(rgb) + ch + reset;
  }
  out += "\n";
}

// Trim the trailing newline; Render() will add its own.
out = out.replace(/\n$/, "");

// Emit a Go file with the rendered banner as a string constant.
const goLiteral = JSON.stringify(out); // safe, produces a Go-compatible "..."
const goSrc = `// Code generated by scripts/gen-banner. DO NOT EDIT.
//
// Source: ascii.rest banner with font="tall", color=["#e67a4c","#4282d7"],
// effect="still". The frame is baked at build time so the binary needs no
// network access and no ascii-rest runtime.
//
// Regenerate with: node scripts/gen-banner/generate.mjs > internal/banner/art.go
//
// Part of ascii.rest by @bas3line (https://github.com/bas3line), MIT licensed.
package banner

// Art is the rendered "OFA" banner as a single ANSI-colored string.
// Each non-space cell carries an SGR 24-bit color escape sequence:
//
//	\\x1b[38;2;<r>;<g>;<b>m<char>\\x1b[0m
//
// The two stops of the fade are #e67a4c (orange) and #4282d7 (blue).
// Cols: ${meta.cols}, Rows: ${meta.rows}.
const Art = ${goLiteral}
`;

writeFileSync(process.argv[2] ?? "art.go", goSrc);
console.error(`wrote ${process.argv[2] ?? "art.go"} (${meta.cols}x${meta.rows})`);

// helper: number of fade steps per theme. Mirrors banner.ts's `steps` constant.
function stepsOf(m) {
  // palette.length = 2 * (steps + 1) for a colored banner.
  return m.palette.length / 2 - 1;
}